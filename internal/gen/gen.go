// Package gen turns an intent tree into the committed markdown docs (DESIGN §8).
//
// Generation is deterministic and churn-free by construction: authored content
// follows tree (insertion) order, every derived block (backlinks, see-also,
// contents maps) is sorted by canonical address, and all fixed strings are
// literal. Re-running
// on unchanged intent is byte-identical, and adding one reference touches only
// the pages on either end of it.
//
// The unit of output is a page: one document element plus the inline subtree it
// hosts (down to the next document boundary). A document with document children
// becomes a directory README.md; a leaf document is a single file; inline
// elements render as sections on their nearest document ancestor's page and are
// linked to by in-page anchor.
package gen

import (
	"sort"
	"strconv"

	"github.com/colchuck-ai/intent/internal/config"
	"github.com/colchuck-ai/intent/internal/tree"
)

// Banner marks a file as generated. It is the first line of every page: the
// "do not edit" boundary for reviewers, and the flag build/check use to tell
// generated docs from a project's own files.
const Banner = "<!-- generated by intent from intent.yaml — do not edit -->"

// File is one generated page: a forward-slash path relative to the output dir
// and its full byte content.
type File struct {
	Path    string
	Content []byte
}

// Build renders the whole tree into pages, sorted by path for a stable result.
// It assumes the tree is valid (the CLI validates first); a dangling target
// degrades to plain text rather than crashing.
func Build(ix *tree.Index, cfg *config.Config) []File {
	s := newSite(ix, cfg)
	files := make([]File, 0, len(s.pageOrder))
	for _, host := range s.pageOrder {
		files = append(files, File{
			Path:    s.file[host],
			Content: s.renderPage(host),
		})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files
}

// site is the precomputed layout of one tree: where every document element's
// file lives, which page hosts each element, and the in-page anchor for the
// inline ones. Rendering reads only from here, so a link never has to recompute
// a path.
type site struct {
	ix  *tree.Index
	cfg *config.Config

	file      map[string]string // document addr -> file path (rel to output dir)
	host      map[string]string // any addr -> hosting document addr
	anchor    map[string]string // any addr -> in-page anchor ("" for document pages)
	pageEls   map[string][]*tree.Element
	pageOrder []string // host addrs in tree order
}

func newSite(ix *tree.Index, cfg *config.Config) *site {
	s := &site{
		ix: ix, cfg: cfg,
		file:    map[string]string{},
		host:    map[string]string{},
		anchor:  map[string]string{},
		pageEls: map[string][]*tree.Element{},
	}

	// A document element becomes a directory if it has a document child.
	hasDocChild := map[string]bool{}
	for _, e := range ix.All() {
		if e.RendersAsDocument() {
			if p := tree.ParentAddr(e.Addr); p != "" {
				hasDocChild[p] = true
			}
		}
	}

	// Assign every element to a page and every document element to a file.
	for _, e := range ix.All() {
		host := s.hostOf(e)
		s.host[e.Addr] = host
		if _, seen := s.pageEls[host]; !seen {
			s.pageOrder = append(s.pageOrder, host)
		}
		s.pageEls[host] = append(s.pageEls[host], e)
		if e.RendersAsDocument() {
			s.file[e.Addr] = filePathFor(e.Addr, hasDocChild[e.Addr])
		}
	}

	// Anchors are page-local: slug each inline element's heading, disambiguating
	// duplicate slugs on the same page the way GitHub does (append -1, -2, …).
	for _, host := range s.pageOrder {
		used := map[string]int{}
		for _, e := range s.pageEls[host] {
			if e.RendersAsDocument() {
				continue // document pages are linked by file, not anchor
			}
			base := slug(displayName(e))
			a := base
			if n := used[base]; n > 0 {
				a = base + "-" + strconv.Itoa(n)
			}
			used[base]++
			s.anchor[e.Addr] = a
		}
	}
	return s
}

// hostOf is the document element that renders e: e itself if it is a document,
// otherwise its nearest document ancestor. Roots are always documents, so the
// walk always terminates.
func (s *site) hostOf(e *tree.Element) string {
	if e.RendersAsDocument() {
		return e.Addr
	}
	for cur := tree.ParentAddr(e.Addr); cur != ""; cur = tree.ParentAddr(cur) {
		if p, ok := s.ix.Get(cur); ok && p.RendersAsDocument() {
			return cur
		}
	}
	return e.Addr // unreachable while the containment invariant holds
}

// seeAlso are the elements related to addr by a shared outgoing edge target —
// e.g. two requirements that mitigate the same risk, or two components that
// fulfill the same requirement. Elements already directly connected to addr (its
// own edge targets and the elements that reference it) are excluded, so the
// section surfaces only relations not already visible in the body or the
// backlinks. The result is address-sorted (DESIGN §8, §10: a derived dual of the
// declared edges).
func (s *site) seeAlso(addr string) []string {
	e, ok := s.ix.Get(addr)
	if !ok {
		return nil
	}
	exclude := map[string]bool{addr: true}
	var targets []string
	for _, edge := range e.Edges {
		exclude[edge.To] = true
		targets = append(targets, edge.To)
	}
	for _, r := range s.ix.Incoming(addr) {
		exclude[r.From] = true
	}

	found := map[string]bool{}
	for _, t := range targets {
		for _, r := range s.ix.Incoming(t) { // every element that also points at t
			if !exclude[r.From] {
				found[r.From] = true
			}
		}
	}
	out := make([]string, 0, len(found))
	for a := range found {
		out = append(out, a)
	}
	sort.Strings(out)
	return out
}

// docChildren are the immediate children of host that render as their own page,
// sorted by address for a stable contents map.
func (s *site) docChildren(host string) []*tree.Element {
	var out []*tree.Element
	for _, e := range s.ix.All() {
		if e.RendersAsDocument() && tree.ParentAddr(e.Addr) == host {
			out = append(out, e)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Addr < out[j].Addr })
	return out
}

// displayName is the element's name, falling back to its key when there is
// none (unreachable today: every kind requires a name).
func displayName(e *tree.Element) string {
	if e.Name != "" {
		return e.Name
	}
	return tree.LastSegment(e.Addr)
}
